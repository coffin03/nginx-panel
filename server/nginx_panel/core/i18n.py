    """取当前语言文案，缺失时回退中文，再回退 key 本身。"""
    text = MESSAGES.get(_current.get(), {}).get(key) or MESSAGES[DEFAULT_LOCALE].get(key) or key
    if params:
        try:
            return text.format(**params)
        except (KeyError, IndexError, ValueError):
            return text
    return text